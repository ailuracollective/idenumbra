use crate::util;
use std::path::PathBuf;

pub fn run(codes: Vec<String>, project: PathBuf, source: Option<PathBuf>, dry_run: bool) -> Result<(), String> {
    let pb = indicatif::ProgressBar::new_spinner();
    pb.set_style(indicatif::ProgressStyle::default_spinner());
    pb.set_message("Installing validators...");
    pb.enable_steady_tick(std::time::Duration::from_millis(80));
    let src_root = util::detect_source(source)?;
    let mut installed = util::read_installed(&project);
    for code in &codes {
        let code_up = code.to_uppercase();
        let code_low = code.to_lowercase();
        let src = src_root.join("crates").join("countries").join(&code_low).join("src");
        if !src.is_dir() {
            return Err(format!("unknown country code: {} (no source at {})", code_up, src.display()));
        }
        let dst = project.join("src").join("idenumbra").join("countries").join(&code_low);
        println!("Adding {} -> {}", code_up, dst.display());
        util::copy_dir_all(&src, &dst, dry_run)?;
        if !installed.iter().any(|c| c.eq_ignore_ascii_case(&code_low)) {
            installed.push(code_low.clone());
        }
    }
    let mod_path = project.join("src").join("idenumbra").join("mod.rs");
    if !mod_path.exists() && !dry_run {
        if let Some(parent) = mod_path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        let dispatcher = "// Auto-generated by idenumbra CLI. Do not edit by hand.\n#![allow(dead_code)]\n";
        std::fs::write(&mod_path, dispatcher).map_err(|e| e.to_string())?;
        println!("  {} {}", console::style("wrote").green(), mod_path.display());
    }
    util::write_manifest(&project, &installed, dry_run)?;
    pb.finish_with_message("Done.");
    Ok(())
}
